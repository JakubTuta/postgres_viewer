CREATE VIEW reporting.book_details AS
SELECT
    b.id AS book_id,
    b.title,
    b.published_year,
    b.price,
    a.name AS author_name,
    a.country AS author_country
FROM public.books AS b
JOIN public.authors AS a ON a.id = b.author_id;

CREATE MATERIALIZED VIEW reporting.order_totals AS
SELECT
    o.id AS order_id,
    o.customer_id,
    o.ordered_at,
    o.status,
    sum(oi.quantity * oi.unit_price) AS total
FROM public.orders AS o
JOIN public.order_items AS oi ON oi.order_id = o.id
GROUP BY o.id, o.customer_id, o.ordered_at, o.status;
